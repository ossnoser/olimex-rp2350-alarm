"""Exercise the real generator/check CLI against disposable output copies."""
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

CLONE = Path(__file__).resolve().parents[1]
REPO = CLONE.parents[1]
TOOL = CLONE / "tools" / "qm_codegen.py"
FILES = ("blinky_ao.hpp", "blinky_ao.cpp", "console_ao.hpp", "console_ao.cpp")


def check(condition, message):
    if not condition:
        raise RuntimeError(message)


def run(directory, expected_code, expected_text, extra=()):
    result = subprocess.run([sys.executable, str(TOOL), "check", "--generated-dir",
                             str(directory), *extra], capture_output=True, text=True, timeout=90)
    output = result.stdout + result.stderr
    check(result.returncode == expected_code and expected_text in output, output)


def main():
    original = {name: (CLONE / "generated" / name).read_bytes() for name in FILES}
    work = REPO / "build" / "blinky-qm-check-tests"
    work.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=work) as temporary:
        root = Path(temporary)
        fixture = root / "generated"
        fixture.mkdir()
        for name in FILES:
            shutil.copyfile(CLONE / "generated" / name, fixture / name)
        run(fixture, 0, "byte-identical")
        changed = fixture / "blinky_ao.cpp"
        changed.write_bytes(changed.read_bytes() + b"\n// deliberately stale test fixture\n")
        run(fixture, 1, "STALE: blinky_ao.cpp")
        changed.write_bytes(original[changed.name])
        missing = fixture / "console_ao.hpp"
        missing.unlink()
        run(fixture, 1, "MISSING: console_ao.hpp")
        missing.write_bytes(original[missing.name])
        (fixture / "unexpected.cpp").write_text("// not generated by this model\n")
        run(fixture, 1, "UNEXPECTED: unexpected.cpp")
        (fixture / "unexpected.cpp").unlink()
        # A fake version banner verifies refusal before any generation occurs.
        fake = root / "wrong-qm"
        fake.write_text("#!/bin/sh\nprintf 'qm 7.0.4\\n'\n")
        fake.chmod(0o755)
        run(fixture, 2, "QM 5.3.0 is required", ("--qm", str(fake)))
    for name, content in original.items():
        check((CLONE / "generated" / name).read_bytes() == content,
              f"Freshness checks modified tracked output: {name}")
    print("Freshness CLI accepts clean output and rejects stale/missing/extra files and wrong QM version.")


if __name__ == "__main__":
    main()
